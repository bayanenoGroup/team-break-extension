function shuffled(n, avoidFirst) {
  const arr = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  // Never start a new round with the message that ended the previous one.
  if (n > 1 && arr[0] === avoidFirst) [arr[0], arr[n - 1]] = [arr[n - 1], arr[0]];
  return arr;
}

// Takes the next message of a pool, persisting the bag in chrome.storage.
export async function nextMessage(pool) {
  const list = MESSAGES[pool];
  const key = `bag:${pool}`;
  const stored = (await chrome.storage.local.get(key))[key] || {};
  let order = Array.isArray(stored.order) ? stored.order : [];
  // A changed pool size (after an update) invalidates the bag.
  if (stored.size !== list.length) order = [];
  if (!order.length) order = shuffled(list.length, stored.last);
  const index = order.shift();
  await chrome.storage.local.set({
    [key]: { order, last: index, size: list.length },
  });
  return list[index];
}
